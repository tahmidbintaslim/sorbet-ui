/* global URL, console */
// Reads templates/<slug>/* and generates lib/templates-source.ts: every template's
// real files, for the Code tab on /templates/<slug>. Imported by gen-blocks.mjs, so it
// runs before dev and build; the output is committed so type-check works without a build.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('../templates/', import.meta.url).pathname;
const out = {};
let files = 0;
for (const slug of readdirSync(root).sort()) {
  const dir = join(root, slug);
  if (!statSync(dir).isDirectory()) continue;
  const names = readdirSync(dir).filter((f) => /\.tsx?$/.test(f));
  if (!names.includes('index.tsx')) throw new Error(`templates/${slug} needs an index.tsx that default-exports the page`);
  // index.tsx first, then the rest by name.
  names.sort((a, b) => (a === 'index.tsx' ? -1 : b === 'index.tsx' ? 1 : a.localeCompare(b)));
  out[slug] = names.map((file) => ({ file, source: readFileSync(join(dir, file), 'utf8') }));
  files += names.length;
}

writeFileSync(
  new URL('../lib/templates-source.ts', import.meta.url),
  `// Generated by scripts/gen-templates.mjs. Do not edit. Import from server components only.\n` +
    `export type TemplateFile = { file: string; source: string };\n` +
    `export const TEMPLATE_SOURCE: Record<string, TemplateFile[]> = {\n${Object.entries(out)
      .map(([slug, list]) => `  ${JSON.stringify(slug)}: ${JSON.stringify(list)},`)
      .join('\n')}\n};\n`,
);
console.log(`gen-templates: ${Object.keys(out).length} templates, ${files} files`);
