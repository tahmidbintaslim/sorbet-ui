/* global URL, console */
// Copies each block's source into lib/blocks-source.ts so the Blocks page can
// show the exact code it renders. Runs before dev and build.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = new URL('../blocks/', import.meta.url).pathname;
const files = readdirSync(dir).filter((f) => f.endsWith('.tsx')).sort();
const entries = files.map((f) => `  ${JSON.stringify(f.replace('.tsx', ''))}: ${JSON.stringify(readFileSync(join(dir, f), 'utf8'))},`);
const out = `// Generated by scripts/gen-blocks.mjs. Do not edit.\nexport const BLOCK_SOURCE: Record<string, string> = {\n${entries.join('\n')}\n};\n`;
writeFileSync(new URL('../lib/blocks-source.ts', import.meta.url), out);
console.log(`gen-blocks: ${files.length} blocks`);
