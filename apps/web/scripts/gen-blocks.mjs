/* global URL, console */
// Scans blocks/<category>/*.tsx and generates:
//  - lib/blocks-meta.ts and lib/blocks-source.ts: block metadata, and each block's exact source (for the Code tab)
//  - components/blocks-registry.ts: the block components, keyed by id
// Each block file starts with 'use client' and a `// @block {"name","description"}` line.
// Runs before dev and build; the outputs are committed so type-check works without a build.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('../blocks/', import.meta.url).pathname;
const blocks = [];
for (const category of readdirSync(root).sort()) {
  const dir = join(root, category);
  if (!statSync(dir).isDirectory()) continue;
  for (const file of readdirSync(dir).filter((f) => f.endsWith('.tsx')).sort()) {
    const raw = readFileSync(join(dir, file), 'utf8');
    const m = raw.match(/^\/\/ @block (\{.*\})$/m);
    if (!m) throw new Error(`blocks/${category}/${file} is missing its // @block {...} line`);
    const { name, description } = JSON.parse(m[1]);
    const id = file.replace('.tsx', '');
    if (blocks.some((b) => b.id === id)) throw new Error(`duplicate block id ${id}`);
    // The metadata line is site plumbing; the copied source should not include it.
    const source = raw.replace(/^\/\/ @block .*\n/m, '');
    blocks.push({ id, category, name, description, source });
  }
}

const meta = blocks.map(({ id, category, name, description }) => ({ id, category, name, description }));
// Three modules so each page loads only what it renders:
// - blocks-meta: names and categories (small; safe anywhere, including client code).
// - blocks-source: the full source text, imported only by server pages that show code.
// - blocks-registry: a server module mapping ids to the blocks; each block file is its
//   own 'use client' boundary, so a page ships only the blocks it actually renders.
writeFileSync(
  new URL('../lib/blocks-meta.ts', import.meta.url),
  `// Generated by scripts/gen-blocks.mjs. Do not edit.\n` +
    `export type BlockMeta = { id: string; category: string; name: string; description: string };\n` +
    `export const BLOCKS: BlockMeta[] = ${JSON.stringify(meta, null, 2)};\n`,
);
writeFileSync(
  new URL('../lib/blocks-source.ts', import.meta.url),
  `// Generated by scripts/gen-blocks.mjs. Do not edit. Import from server components only.\n` +
    `export const BLOCK_SOURCE: Record<string, string> = {\n${blocks.map((b) => `  ${JSON.stringify(b.id)}: ${JSON.stringify(b.source)},`).join('\n')}\n};\n`,
);
writeFileSync(
  new URL('../components/blocks-registry.ts', import.meta.url),
  `// Generated by scripts/gen-blocks.mjs. Do not edit. Import from server components only.\nimport type { ComponentType } from 'react';\n` +
    blocks.map((b) => `import ${b.id} from '@/blocks/${b.category}/${b.id}';`).join('\n') +
    `\n\nexport const BLOCK_COMPONENTS: Record<string, ComponentType> = {\n${blocks.map((b) => `  ${b.id},`).join('\n')}\n};\n`,
);
console.log(`gen-blocks: ${blocks.length} blocks in ${new Set(blocks.map((b) => b.category)).size} categories`);
