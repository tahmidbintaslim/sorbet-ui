/* global URL, console, Buffer */
// Generates everything the component docs pages show, so none of it is hand-copied:
//  - lib/docs-examples-meta.ts     example ids, titles and descriptions per component (small; client-safe)
//  - lib/docs-examples-source.ts   each example's exact source (server pages only)
//  - components/docs/examples-registry.ts  the example components, keyed by slug and id (server only)
//  - lib/docs-api.ts               props tables read from packages/react/src with the TypeScript compiler API
//  - lib/docs-search-index.ts      the search index (components, examples, guide sections), loaded on demand
// Each example is docs-examples/<slug>/<nn>-<id>.tsx: 'use client', then a
// `// @example {"title","description"}` line. Runs before dev and build; outputs are committed.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const SRC = here('../../../packages/react/src/');
const EXAMPLES = here('../docs-examples/');

// ---------------------------------------------------------------------------
// Catalog (lib/catalog.ts has no imports, so it can be transpiled and loaded here)
// ---------------------------------------------------------------------------
const catalogJs = ts.transpileModule(readFileSync(here('../lib/catalog.ts'), 'utf8'), {
  compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 },
}).outputText;
const { CATALOG } = await import(`data:text/javascript;base64,${Buffer.from(catalogJs).toString('base64')}`);

// ---------------------------------------------------------------------------
// Examples
// ---------------------------------------------------------------------------
const examples = {};
let total = 0;
for (const { slug } of CATALOG) {
  const dir = join(EXAMPLES, slug);
  if (!existsSync(dir)) throw new Error(`docs-examples/${slug}/ is missing: every component needs examples`);
  examples[slug] = readdirSync(dir)
    .filter((f) => f.endsWith('.tsx'))
    .sort()
    .map((file) => {
      const raw = readFileSync(join(dir, file), 'utf8');
      const m = raw.match(/^\/\/ @example (\{.*\})$/m);
      if (!m) throw new Error(`docs-examples/${slug}/${file} is missing its // @example {...} line`);
      if (!raw.startsWith("'use client';")) throw new Error(`docs-examples/${slug}/${file} must start with 'use client';`);
      const { title, description } = JSON.parse(m[1]);
      const id = file.replace(/^\d+-/, '').replace('.tsx', '');
      // The metadata line is site plumbing; the shown source should not include it.
      const source = raw.replace(/^\/\/ @example .*\n/m, '');
      return { id, file, title, description, source };
    });
  const ids = examples[slug].map((e) => e.id);
  if (new Set(ids).size !== ids.length) throw new Error(`duplicate example id in docs-examples/${slug}`);
  if (ids.length < 4) throw new Error(`docs-examples/${slug} has ${ids.length} examples; at least 4 are expected`);
  total += ids.length;
}

const header = (extra = '') => `// Generated by scripts/gen-docs.mjs. Do not edit.${extra}\n`;
const SERVER_ONLY = ' Import from server components only.';

writeFileSync(
  here('../lib/docs-examples-meta.ts'),
  header() +
    `export type ExampleMeta = { id: string; title: string; description: string };\n` +
    `export const EXAMPLES: Record<string, ExampleMeta[]> = ${JSON.stringify(
      Object.fromEntries(Object.entries(examples).map(([s, list]) => [s, list.map(({ id, title, description }) => ({ id, title, description }))])),
      null,
      2,
    )};\n`,
);
writeFileSync(
  here('../lib/docs-examples-source.ts'),
  header(SERVER_ONLY) +
    `export const EXAMPLE_SOURCE: Record<string, Record<string, string>> = {\n${Object.entries(examples)
      .map(([s, list]) => `  ${JSON.stringify(s)}: {\n${list.map((e) => `    ${JSON.stringify(e.id)}: ${JSON.stringify(e.source)},`).join('\n')}\n  },`)
      .join('\n')}\n};\n`,
);
const ident = (slug, id) => `${slug}_${id}`.replace(/[^A-Za-z0-9]+(.)?/g, (_m, c) => (c ? c.toUpperCase() : '')).replace(/^./, (c) => c.toUpperCase());
writeFileSync(
  here('../components/docs/examples-registry.ts'),
  header(SERVER_ONLY) +
    `import type { ComponentType } from 'react';\n` +
    Object.entries(examples)
      .flatMap(([s, list]) => list.map((e) => `import ${ident(s, e.id)} from '@/docs-examples/${s}/${e.file.replace('.tsx', '')}';`))
      .join('\n') +
    `\n\nexport const EXAMPLE_COMPONENTS: Record<string, Record<string, ComponentType>> = {\n${Object.entries(examples)
      .map(([s, list]) => `  ${JSON.stringify(s)}: {\n${list.map((e) => `    ${JSON.stringify(e.id)}: ${ident(s, e.id)},`).join('\n')}\n  },`)
      .join('\n')}\n};\n`,
);

// ---------------------------------------------------------------------------
// API reference: props, types, defaults and JSDoc from packages/react/src
// ---------------------------------------------------------------------------
const files = readdirSync(SRC)
  .filter((f) => f.endsWith('.tsx') && !/\.(stories|test)\./.test(f))
  .map((f) => ({ name: f, sf: ts.createSourceFile(f, readFileSync(join(SRC, f), 'utf8'), ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX) }));

// Shared unions that some components import from @sorbet-ui/core instead of declaring.
const SHARED = {
  SorbetVariant: "'solid' | 'soft' | 'outlined' | 'ghost' | 'plain'",
  SorbetColor: "'primary' | 'secondary' | 'success' | 'warning' | 'danger' | 'info' | 'neutral'",
  SorbetSize: "'xs' | 'sm' | 'md' | 'lg' | 'xl'",
};

const isExported = (n) => !!n.modifiers?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword);
const squash = (s) => s.replace(/\s+/g, ' ').replace(/^\| /, '').trim();

function declarations(sf) {
  const out = { interfaces: {}, aliases: {}, exports: new Set(), reexports: new Set() };
  for (const st of sf.statements) {
    if (ts.isInterfaceDeclaration(st)) out.interfaces[st.name.text] = st;
    else if (ts.isTypeAliasDeclaration(st)) out.aliases[st.name.text] = st;
    else if (ts.isVariableStatement(st) && isExported(st)) for (const d of st.declarationList.declarations) out.exports.add(d.name.getText());
    else if (ts.isFunctionDeclaration(st) && isExported(st) && st.name) out.exports.add(st.name.text);
    else if (ts.isExportDeclaration(st) && st.exportClause && ts.isNamedExports(st.exportClause))
      for (const e of st.exportClause.elements) if (!e.isTypeOnly && !st.isTypeOnly) out.reexports.add(e.name.text);
  }
  return out;
}
const DECLS = new Map(files.map((f) => [f.name, declarations(f.sf)]));

// Inline local aliases that are plain unions of literals (SorbetSize → 'xs' | 'sm' | …).
function typeText(node, decl, depth = 0) {
  let text = squash(node.getText());
  if (depth > 3) return text;
  return text.replace(/\b[A-Z][A-Za-z]+\b/g, (name) => {
    const alias = decl.aliases[name];
    if (alias) {
      const t = alias.type;
      const literal = (x) => ts.isLiteralTypeNode(x) || (ts.isTypeReferenceNode(x) && (decl.aliases[x.typeName.getText()] || SHARED[x.typeName.getText()]));
      if (ts.isUnionTypeNode(t) ? t.types.every(literal) : ts.isTypeReferenceNode(t) && literal(t)) return typeText(t, decl, depth + 1);
      return name;
    }
    return SHARED[name] ?? name;
  });
}

function jsdoc(node) {
  const docs = ts.getJSDocCommentsAndTags(node).filter(ts.isJSDoc);
  const doc = docs[docs.length - 1];
  if (!doc) return { description: '', def: undefined };
  const description = squash(ts.getTextOfJSDocComment(doc.comment) ?? '');
  const tag = doc.tags?.find((t) => t.tagName.text === 'default');
  return { description, def: tag ? squash(ts.getTextOfJSDocComment(tag.comment) ?? '') : undefined };
}

// MUI component an interface extends, e.g. Omit<MuiButtonProps, …> → Button.
function muiBase(node) {
  const m = node.getText().match(/\bMui([A-Z][A-Za-z]+)Props\b/);
  return m ? m[1] : undefined;
}
const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
const muiHref = (name) =>
  name === 'DatePicker' ? 'https://mui.com/x/api/date-pickers/date-picker/' : `https://mui.com/material-ui/api/${kebab(name)}/`;

// Same prop declared on several union members: list each distinct type once.
function joinType(member, type) {
  member.types ??= [member.type];
  if (member.types.includes(type)) return;
  member.types.push(type);
  member.type = member.types.join(' | ');
}

// Members of an interface or alias, following local `extends` and unions of local interfaces.
function collect(typeName, decl, seen = new Set()) {
  if (seen.has(typeName)) return { members: [], mui: undefined };
  seen.add(typeName);
  const members = [];
  let mui;
  const add = (member, only) => {
    if (!ts.isPropertySignature(member) && !ts.isMethodSignature(member)) return;
    const name = member.name.getText().replace(/^['"]|['"]$/g, '');
    const { description, def } = jsdoc(member);
    const type = ts.isPropertySignature(member) && member.type ? typeText(member.type, decl) : squash(member.getText());
    const existing = members.find((m) => m.name === name);
    if (existing) {
      // Same prop on several union members (Progress `type`): join the types.
      joinType(existing, type);
      existing.required = existing.required && !member.questionToken;
      return;
    }
    members.push({ name, type, required: !member.questionToken, def, description: only ? `${description}${description ? ' ' : ''}(${only} only)`.replace(/\((\w+) only\) \(\1 only\)/, '($1 only)') : description });
  };
  const iface = decl.interfaces[typeName];
  const alias = decl.aliases[typeName];
  if (iface) {
    for (const h of iface.heritageClauses ?? [])
      for (const t of h.types) {
        const base = t.expression.getText();
        if (decl.interfaces[base]) {
          const inherited = collect(base, decl, seen);
          for (const m of inherited.members) if (!members.some((x) => x.name === m.name)) members.push(m);
          mui ??= inherited.mui;
        } else mui ??= muiBase(t);
      }
    // Own members first in the table, inherited (shared base) ones after.
    const own = [];
    for (const m of iface.members) {
      const before = members.length;
      add(m);
      if (members.length > before) own.push(members.pop());
      else {
        // Overrides an inherited member: the own declaration wins.
        const name = m.name?.getText().replace(/^['"]|['"]$/g, '');
        const i = members.findIndex((x) => x.name === name);
        if (i >= 0) {
          const [old] = members.splice(i, 1);
          add(m);
          const fresh = members.pop();
          own.push({ ...fresh, description: fresh.description || old.description });
        }
      }
    }
    members.unshift(...own);
  } else if (alias) {
    const t = alias.type;
    if (ts.isUnionTypeNode(t) && t.types.every((x) => ts.isTypeReferenceNode(x) && decl.interfaces[x.typeName.getText()])) {
      // A union of local interfaces: one table, noting props that only one member has.
      const parts = t.types.map((x) => ({ name: x.typeName.getText(), ...collect(x.typeName.getText(), decl, new Set(seen)) }));
      for (const part of parts)
        for (const m of part.members) {
          const shared = parts.every((p) => p.members.some((x) => x.name === m.name));
          const existing = members.find((x) => x.name === m.name);
          if (existing) {
            joinType(existing, m.type);
            existing.required = existing.required && m.required;
          } else {
            const only = shared ? '' : part.name.replace(/Progress|Props/g, '').toLowerCase();
            members.push({ ...m, description: only ? `${m.description} (${only} only)`.trim() : m.description });
          }
        }
    } else if (ts.isTypeLiteralNode(t)) {
      for (const m of t.members) add(m);
    } else mui = muiBase(t) ?? (ts.isTypeReferenceNode(t) ? muiBase(t) : undefined);
  }
  return { members, mui };
}

// Default values from the component's own destructuring (`size = 'md'`).
function defaultsFor(typeNames, sf) {
  const out = {};
  const scopes = [];
  const visit = (n) => {
    if (ts.isCallExpression(n) && /forwardRef$/.test(n.expression.getText()) && n.typeArguments?.[1]) {
      if (typeNames.some((t) => n.typeArguments[1].getText().startsWith(t))) scopes.push(n);
    } else if ((ts.isFunctionDeclaration(n) || ts.isArrowFunction(n) || ts.isFunctionExpression(n)) && n.parameters[0]?.type) {
      const t = n.parameters[0].type.getText();
      if (typeNames.some((name) => t === name || t.startsWith(`${name}<`))) scopes.push(n);
    }
    ts.forEachChild(n, visit);
  };
  visit(sf);
  for (const scope of scopes) {
    let pattern;
    const find = (n) => {
      if (pattern) return;
      if (ts.isObjectBindingPattern(n)) pattern = n;
      else ts.forEachChild(n, find);
    };
    find(scope);
    for (const el of pattern?.elements ?? []) {
      if (!el.initializer || el.dotDotDotToken) continue;
      const name = (el.propertyName ?? el.name).getText().replace(/^['"]|['"]$/g, '');
      out[name] ??= squash(el.initializer.getText());
    }
  }
  return out;
}

function findComponent(name) {
  for (const f of files) {
    const d = DECLS.get(f.name);
    if (d.exports.has(name)) return { file: f, decl: d, own: true };
  }
  for (const f of files) {
    const d = DECLS.get(f.name);
    if (d.reexports.has(name)) return { file: f, decl: d, own: false };
  }
  return undefined;
}

function propsTypeOf(name, file, decl) {
  let found;
  const visit = (n) => {
    if (found) return;
    if (ts.isVariableDeclaration(n) && n.name.getText() === name && n.initializer) {
      const call = ts.isAsExpression(n.initializer) ? n.initializer.expression : n.initializer;
      if (ts.isCallExpression(call) && call.typeArguments?.[1]) found = call.typeArguments[1].getText().replace(/<.*/, '');
    }
    ts.forEachChild(n, visit);
  };
  visit(file.sf);
  if (found) return found;
  for (const guess of [`${name}Props`, `Sorbet${name}Props`, `${name}ItemProps`]) if (decl.interfaces[guess] || decl.aliases[guess]) return guess;
  return undefined;
}

const ORDER = ['variant', 'color', 'size'];
function table(typeName, file, decl) {
  const { members, mui } = collect(typeName, decl);
  const union = decl.aliases[typeName] && ts.isUnionTypeNode(decl.aliases[typeName].type) ? decl.aliases[typeName].type.types.map((t) => t.getText()) : [];
  const defaults = defaultsFor([typeName, ...union], file.sf);
  const props = members.map((m) => ({
    name: m.name,
    type: m.type,
    required: m.required,
    default: m.def ?? defaults[m.name] ?? '',
    description: m.description,
  }));
  // The shared variant / color / size API leads every table.
  props.sort((a, b) => (ORDER.indexOf(a.name) + 1 || 99) - (ORDER.indexOf(b.name) + 1 || 99));
  return { props, mui };
}

const api = {};
for (const entry of CATALOG) {
  api[entry.slug] = [];
  for (const name of entry.imports) {
    if (/^[a-z]/.test(name)) continue; // helpers such as dayjs
    const c = findComponent(name);
    if (!c) throw new Error(`gen-docs: ${name} is not exported from packages/react/src`);
    const typeName = c.own ? propsTypeOf(name, c.file, c.decl) : undefined;
    const { props, mui } = typeName ? table(typeName, c.file, c.decl) : { props: [], mui: undefined };
    const base = mui ?? (props.length === 0 ? name : undefined);
    api[entry.slug].push({ name, kind: 'component', props, mui: base ? { name: base, href: muiHref(base) } : null });
  }
  for (const typeName of entry.types ?? []) {
    const f = files.find((x) => DECLS.get(x.name).interfaces[typeName]);
    if (!f) throw new Error(`gen-docs: type ${typeName} not found in packages/react/src`);
    const { props } = table(typeName, f, DECLS.get(f.name));
    api[entry.slug].push({ name: typeName, kind: 'type', props, mui: null });
  }
}
writeFileSync(
  here('../lib/docs-api.ts'),
  header(SERVER_ONLY) +
    `export type ApiProp = { name: string; type: string; required: boolean; default: string; description: string };\n` +
    `export type ApiTable = { name: string; kind: 'component' | 'type'; props: ApiProp[]; mui: { name: string; href: string } | null };\n` +
    `export const API: Record<string, ApiTable[]> = ${JSON.stringify(api, null, 2)};\n`,
);

// ---------------------------------------------------------------------------
// Search index: components, their examples, and the guide pages' sections
// ---------------------------------------------------------------------------
const index = [];
const navJs = ts.transpileModule(readFileSync(here('../lib/docs-nav.ts'), 'utf8'), {
  compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 },
}).outputText;
const { DOC_PAGES } = await import(`data:text/javascript;base64,${Buffer.from(navJs).toString('base64')}`);
for (const g of DOC_PAGES) {
  index.push({ title: g.title, href: g.href, group: 'Guides', hint: 'Guide', keywords: g.description });
  const file = here(`../${g.file}`);
  if (!existsSync(file)) throw new Error(`${g.file} is listed in lib/docs-nav.ts but does not exist`);
  const raw = readFileSync(file, 'utf8');
  // <Section id="x" title="Y"> and <DocHeading id="x" level={2}>Y</DocHeading> both count.
  for (const m of raw.matchAll(/<Section\s+id="([^"]+)"\s+title="([^"]+)"/g))
    index.push({ title: m[2], href: `${g.href}#${m[1]}`, group: 'Guides', hint: g.title });
  for (const m of raw.matchAll(/<DocHeading\s+id="([^"]+)"\s+level=\{2\}>\s*([^<{]+?)\s*</g))
    index.push({ title: m[2], href: `${g.href}#${m[1]}`, group: 'Guides', hint: g.title });
}
index.push({ title: 'All components', href: '/docs/components', group: 'Components', hint: 'Catalog' });
for (const c of CATALOG) {
  index.push({ title: c.name, href: `/docs/components/${c.slug}`, group: 'Components', hint: c.description, keywords: c.imports.join(' ') });
}
for (const c of CATALOG) {
  for (const e of examples[c.slug]) index.push({ title: e.title, href: `/docs/components/${c.slug}#${e.id}`, group: 'Examples', hint: c.name, keywords: e.description });
}
writeFileSync(
  here('../lib/docs-search-index.ts'),
  header(' Loaded on demand by the docs search.') +
    `export type SearchEntry = { title: string; href: string; group: 'Guides' | 'Components' | 'Examples'; hint: string; keywords?: string };\n` +
    `export const SEARCH_INDEX: SearchEntry[] = ${JSON.stringify(index, null, 2)};\n`,
);

console.log(
  `gen-docs: ${total} examples for ${CATALOG.length} components, ${Object.values(api).flat().reduce((n, t) => n + t.props.length, 0)} documented props, ${index.length} search entries`,
);
